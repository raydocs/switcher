import Foundation

// The PATH shims that make the pointer take effect, and the one rc-file line that puts them first.

public enum CLIShim {
    public static let marker = "# switcher-shim v1"
    public static let rcBegin = "# >>> switcher cli shims >>>"
    public static let rcEnd = "# <<< switcher cli shims <<<"

    /// The shim for `kind`: POSIX sh, no dependencies. When the variable is already set (Orca,
    /// token-arcade, `switcher cli exec`, a nested launch) or `SWITCHER_BYPASS=1`, it does not read
    /// the pointer. Otherwise `default` or anything invalid leaves the variable unset; a valid
    /// profile path (`<root>/<name>`, a real folder under a real `<root>`) sets it, byte for byte.
    /// For `agy`, an active or inherited `ANTIGRAVITY_GEMINI_DIR` also refreshes the profile's
    /// keyring-bypass marker and passes `--gemini_dir` on commands whose CLI parser expects it.
    public static func script(_ kind: CLIKind, env: CLIEnv, realBinary: String) -> String {
        let v = kind.envVar
        let root = env.profilesRoot(kind)
        let agyPre = kind == .agy ? """
        agy_explicit=
        agy_explicit_dir=
        agy_want_dir=
        for a in "$@"; do
          if [ -n "$agy_want_dir" ]; then
            agy_explicit_dir=$a
            break
          fi
          case "$a" in
            --gemini_dir=*|-gemini_dir=*) agy_explicit=1; agy_explicit_dir=${a#*=}; break ;;
            --gemini_dir|-gemini_dir) agy_explicit=1; agy_want_dir=1 ;;
          esac
        done

        """ : ""
        let agyGuard = kind == .agy ? " && [ -z \"$agy_explicit\" ]" : ""
        let agyPost = kind == .agy ? """
        if [ "${SWITCHER_BYPASS:-}" != 1 ]; then
          agy_iso_dir=
          if [ -z "$agy_explicit" ] && [ -n "${ANTIGRAVITY_GEMINI_DIR:-}" ]; then
            agy_iso_dir=$ANTIGRAVITY_GEMINI_DIR
          elif [ -n "$agy_explicit" ]; then
            case "$agy_explicit_dir" in
              \(shellQuote(root + "/"))*) agy_iso_dir=$agy_explicit_dir ;;
              *)
                if [ -n "${ANTIGRAVITY_GEMINI_DIR:-}" ] && [ "$ANTIGRAVITY_GEMINI_DIR" != \(shellQuote(env.defaultFolder(.agy))) ]; then
                  agy_iso_dir=$ANTIGRAVITY_GEMINI_DIR
                fi
                ;;
            esac
          fi
          if [ -n "$agy_iso_dir" ] && [ "$agy_iso_dir" != \(shellQuote(env.defaultFolder(.agy))) ]; then
            agy_marker="$agy_iso_dir/antigravity-cli/cache/antigravity-keyring-unavailable"
            agy_marker_ok=
            if [ -d "$agy_iso_dir" ] && [ ! -L "$agy_iso_dir" ]; then
              if [ ! -e "$agy_iso_dir/antigravity-cli" ]; then
                (umask 077 && mkdir "$agy_iso_dir/antigravity-cli") 2>/dev/null || true
              fi
              if [ -d "$agy_iso_dir/antigravity-cli" ] && [ ! -L "$agy_iso_dir/antigravity-cli" ]; then
                if [ ! -e "$agy_iso_dir/antigravity-cli/cache" ]; then
                  (umask 077 && mkdir "$agy_iso_dir/antigravity-cli/cache") 2>/dev/null || true
                fi
                if [ -d "$agy_iso_dir/antigravity-cli/cache" ] && [ ! -L "$agy_iso_dir/antigravity-cli/cache" ] && [ ! -L "$agy_marker" ]; then
                  if (umask 077 && : > "$agy_marker") 2>/dev/null && chmod 600 "$agy_marker" 2>/dev/null && [ -f "$agy_marker" ] && [ ! -L "$agy_marker" ]; then
                    agy_marker_ok=1
                  fi
                fi
              fi
            fi
            if [ -z "$agy_marker_ok" ]; then
              printf 'switcher: cannot isolate Antigravity CLI profile "%s" (keyring marker failed); refusing to start\\n' "$agy_iso_dir" >&2
              exit 1
            fi
          fi
          if [ -z "$agy_explicit" ] && [ -n "${ANTIGRAVITY_GEMINI_DIR:-}" ]; then
            agy_dir=$ANTIGRAVITY_GEMINI_DIR
            case "${1:-}" in
              agentapi|multicall|plugin-cli) ;;
              *)
                if [ "$#" -eq 0 ] && [ -n "${AGY_CLI_CDE_AUTH_ACTION:-}" ]; then
                  :
                else
                  set -- "--gemini_dir=$agy_dir" "$@"
                fi
                ;;
            esac
          fi
        fi

        """ : ""
        return """
        #!/bin/sh
        \(marker) \(kind.rawValue)
        # Generated by Switcher. Picks the \(kind.displayName) account for new processes; see `switcher cli doctor`.
        real=\(shellQuote(realBinary))
        \(agyPre)if [ -z "${\(v)+x}" ] && [ "${SWITCHER_BYPASS:-}" != 1 ]\(agyGuard); then
          p=
          if [ -r \(shellQuote(env.pointer(kind))) ]; then IFS= read -r p < \(shellQuote(env.pointer(kind))) || true; fi
          case "$p" in
            ''|default) ;;
            \(shellQuote(root + "/"))*)
              name=${p#\(shellQuote(root + "/"))}
              valid=1
              # Exactly CLIPath.isValidName: 1-64 of [A-Za-z0-9._-] (spelled out: ranges follow the
              # locale in some shells), not starting with . or -, never default or all digits.
              case "$name" in
                ''|[Dd][Ee][Ff][Aa][Uu][Ll][Tt]|.*|-*|*[!ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789._-]*) valid= ;;
                *[!0123456789]*) ;;
                *) valid= ;;
              esac
              if [ "${#name}" -gt 64 ]; then valid=; fi
              if [ -z "$valid" ]; then
                if [ -t 2 ]; then printf 'switcher: ignoring an unexpected %s pointer; using the default account\\n' \(shellQuote(kind.displayName)) >&2; fi
              elif [ -d \(shellQuote(root)) ] && [ ! -L \(shellQuote(root)) ] && [ -d "$p" ] && [ ! -L "$p" ]; then
                \(v)=$p
                export \(v)
              elif [ -t 2 ]; then
                printf 'switcher: the %s account "%s" is gone; using the default account\\n' \(shellQuote(kind.displayName)) "$p" >&2
              fi
              ;;
            *)
              if [ -t 2 ]; then printf 'switcher: ignoring an unexpected %s pointer; using the default account\\n' \(shellQuote(kind.displayName)) >&2; fi
              ;;
          esac
        fi
        \(agyPost)if [ "$real" -ef "$0" ]; then
          printf 'switcher: the %s shim points at itself; run `switcher cli install` again\\n' \(shellQuote(kind.command)) >&2
          exit 127
        fi
        exec "$real" "$@"

        """
    }

    /// True when `path` resolves to an executable regular file (never a directory).
    public static func isRegularExecutable(_ path: String) -> Bool {
        var st = stat()
        return stat(path, &st) == 0 && (st.st_mode & S_IFMT) == S_IFREG && access(path, X_OK) == 0
    }

    public static func isShim(_ path: String) -> Bool {
        guard let fh = FileHandle(forReadingAtPath: path) else { return false }
        defer { try? fh.close() }
        var st = stat()
        guard fstat(fh.fileDescriptor, &st) == 0, (st.st_mode & S_IFMT) == S_IFREG else { return false }
        guard let data = try? fh.read(upToCount: 128) else { return false }
        return String(decoding: data, as: UTF8.self).contains(marker)
    }

    /// The real binary: `~/.local/bin/<cmd>` first (Claude's and agy's own installers keep their
    /// launchers there), then absolute `PATH` entries, then standard Homebrew/usr-local folders.
    public static func findRealBinary(_ kind: CLIKind, env: CLIEnv, path: String = ProcessInfo.processInfo.environment["PATH"] ?? "") -> String? {
        if let given = env.realBinaries[kind] { return given.hasPrefix("/") ? given : nil }
        var dirs = [env.home + "/.local/bin"]
        dirs += path.split(separator: ":").map { CLIPath.trimmed(String($0)) }.filter { $0.hasPrefix("/") }
        dirs += env.fallbackSearchDirs.map { CLIPath.trimmed($0) }.filter { $0.hasPrefix("/") }
        let candidates = dirs.map { ($0 == "/" ? "" : $0) + "/" + kind.command }
        return candidates.first { c in
            !c.hasPrefix(env.shimDir + "/") && isRegularExecutable(c) && !isShim(c)
        }
    }

    /// Write every found CLI's shim (0755, atomically). Returns the real binary each one runs.
    @discardableResult
    public static func installShims(env: CLIEnv, path: String = ProcessInfo.processInfo.environment["PATH"] ?? "") throws -> [CLIKind: String] {
        var out: [CLIKind: String] = [:]
        try FileManager.default.createDirectory(atPath: env.shimDir, withIntermediateDirectories: true)
        for kind in CLIKind.allCases {
            guard let real = findRealBinary(kind, env: env, path: path), real.hasPrefix("/") else { continue }
            let url = URL(fileURLWithPath: env.shim(kind))
            try FS.atomicWrite(Data(script(kind, env: env, realBinary: real).utf8), to: url)
            guard chmod(url.path, 0o755) == 0 else { throw POSIXError.current("making \(url.path) executable") }
            out[kind] = real
        }
        return out
    }

    /// The real binary a shim on disk runs, read back from it.
    public static func realBinary(ofShim path: String) -> String? {
        guard let text = try? String(contentsOfFile: path, encoding: .utf8), text.contains(marker) else { return nil }
        for line in text.split(separator: "\n") where line.hasPrefix("real='") && line.hasSuffix("'") {
            return String(line.dropFirst(6).dropLast()).replacingOccurrences(of: "'\\''", with: "'")
        }
        return nil
    }

    public static func uninstallShims(env: CLIEnv) {
        for kind in CLIKind.allCases where isShim(env.shim(kind)) { unlink(env.shim(kind)) }
    }

    // MARK: rc file

    static func block(_ env: CLIEnv) -> String {
        "\(rcBegin)\nexport PATH=\(shellQuote(env.shimDir)):\"$PATH\"\n\(rcEnd)\n"
    }

    /// `text` without Switcher's blocks, and how many were removed. Only complete, well-formed
    /// blocks (begin line, then end line, no nesting) are removed; any other arrangement of the
    /// marker lines throws and nothing is changed, so a half-deleted block never swallows the
    /// lines that follow it.
    static func strip(_ text: String, rc: String) throws -> (text: String, removed: Int) {
        var out: [Substring] = [], inside = false, removed = 0
        let bad = SwitcherError.message("the Switcher lines in \(rc) are incomplete or duplicated: fix or remove the Switcher lines in \(rc) by hand")
        for line in text.split(separator: "\n", omittingEmptySubsequences: false) {
            if line == rcBegin {
                if inside { throw bad }
                inside = true
            } else if line == rcEnd {
                if !inside { throw bad }
                inside = false
                removed += 1
            } else if !inside {
                out.append(line)
            }
        }
        if inside { throw bad }
        var s = out.joined(separator: "\n")
        while s.hasSuffix("\n\n") { s.removeLast() }
        return (s, removed)
    }

    public enum RCState: Equatable, Sendable {
        case absent
        /// Present and the last thing in the file, so nothing later puts another CLI first.
        case last
        /// Present, but lines after it may push other folders ahead of the shims.
        case notLast
        /// Incomplete, nested or unbalanced marker lines.
        case malformed
    }

    public static func rcState(_ text: String) -> RCState {
        guard text.contains(rcBegin) || text.contains(rcEnd) else { return .absent }
        guard let stripped = try? strip(text, rc: ""), stripped.removed > 0 else { return .malformed }
        if stripped.removed > 1 { return .notLast }
        let tail = text.components(separatedBy: rcEnd).last ?? ""
        return tail.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty ? .last : .notLast
    }

    /// The rc file's text. Only "does not exist" (no file and no symlink) is an empty file; any
    /// broken symlink, directory, read error or decoding problem throws so the file is untouched.
    static func readRC(_ rc: String) throws -> String {
        var lst = stat()
        if lstat(rc, &lst) != 0 {
            if errno == ENOENT { return "" }
            throw POSIXError.current("reading \(rc)")
        }
        var st = stat()
        if stat(rc, &st) != 0 {
            if (lst.st_mode & S_IFMT) == S_IFLNK {
                throw SwitcherError.message("\(rc) is a broken symlink; it was left untouched")
            }
            throw POSIXError.current("reading \(rc)")
        }
        guard (st.st_mode & S_IFMT) == S_IFREG else {
            throw SwitcherError.message("\(rc) is not a regular file; it was left untouched")
        }
        let data: Data
        do { data = try Data(contentsOf: URL(fileURLWithPath: rc)) } catch {
            throw SwitcherError.message("cannot read \(rc) (\(error.localizedDescription)); it was left untouched")
        }
        guard let text = String(data: data, encoding: .utf8) else {
            throw SwitcherError.message("\(rc) is not valid UTF-8; it was left untouched")
        }
        return text
    }

    /// Put the block at the very end of `rc` (moving it if it is elsewhere). Keeps a one-time
    /// backup of the file as it was before Switcher first touched it.
    public static func installRC(_ rc: String, env: CLIEnv) throws {
        let old = try readRC(rc)
        let stripped = try strip(old, rc: rc)
        if rcState(old) == .last, old.contains(block(env)) { return }
        if !old.isEmpty { try writeBackupOnce(Data(old.utf8), to: rc + ".before-switcher") }
        var base = stripped.text
        if !base.isEmpty, !base.hasSuffix("\n") { base += "\n" }
        let new = base + (base.isEmpty ? "" : "\n") + block(env)
        try writeKeepingMode(new, to: rc)
    }

    public static func validateUninstallRC(_ rcs: [String]) throws {
        for rc in rcs {
            let old = try readRC(rc)
            _ = try strip(old, rc: rc)
        }
    }

    public static func uninstallRC(_ rc: String) throws {
        let old = try readRC(rc)
        let stripped = try strip(old, rc: rc)
        guard stripped.removed > 0 else { return }
        var s = stripped.text
        if !s.isEmpty, !s.hasSuffix("\n") { s += "\n" }
        try writeKeepingMode(s, to: rc)
    }

    /// The one-time backup: created exclusively (never through a symlink), 0600 whatever the
    /// original's mode or the umask (the file may hold API keys), flushed to disk. An existing
    /// regular file is the earlier backup and stays; anything else in the way is an error.
    static func writeBackupOnce(_ data: Data, to path: String) throws {
        let fd = open(path, O_WRONLY | O_CREAT | O_EXCL | O_NOFOLLOW, 0o600)
        if fd < 0 {
            if errno == EEXIST {
                var st = stat()
                if lstat(path, &st) == 0, (st.st_mode & S_IFMT) == S_IFREG { return }
                throw SwitcherError.message("\(path) exists and is not a regular file; move it away and run install again")
            }
            throw POSIXError.current("creating the backup \(path)")
        }
        var ok = fchmod(fd, 0o600) == 0
        if ok {
            ok = data.withUnsafeBytes { raw -> Bool in
                var off = 0
                while off < raw.count {
                    let n = write(fd, raw.baseAddress! + off, raw.count - off)
                    if n < 0 { if errno == EINTR { continue }; return false }
                    off += n
                }
                return true
            }
        }
        if ok { ok = fsync(fd) == 0 }
        let err = errno
        close(fd)
        if !ok {
            unlink(path)
            errno = err
            throw POSIXError.current("writing the backup \(path)")
        }
    }

    /// The user's rc file keeps its permissions (and stays a regular file: a symlinked rc has its
    /// resolved target replaced atomically so the symlink stays and no partial write can truncate it).
    static func writeKeepingMode(_ text: String, to rc: String) throws {
        var st = stat()
        if lstat(rc, &st) == 0, (st.st_mode & S_IFMT) == S_IFLNK {
            guard let resolved = realpath(rc, nil) else {
                throw SwitcherError.message("\(rc) is a broken symlink; it was left untouched")
            }
            defer { free(resolved) }
            let target = String(cString: resolved)
            var tst = stat()
            guard lstat(target, &tst) == 0, (tst.st_mode & S_IFMT) == S_IFREG else {
                throw SwitcherError.message("\(target) is not a regular file; it was left untouched")
            }
            let mode = tst.st_mode & 0o777
            try FS.atomicWrite(Data(text.utf8), to: URL(fileURLWithPath: target))
            _ = chmod(target, mode)
            return
        }
        let mode = lstat(rc, &st) == 0 ? st.st_mode & 0o777 : 0o644
        try FS.atomicWrite(Data(text.utf8), to: URL(fileURLWithPath: rc))
        _ = chmod(rc, mode)
    }
}
